package org.ikasan.studio.boot.flow.routerflow;

import jakarta.annotation.Resource;
import org.ikasan.builder.BuilderFactory;
import org.ikasan.builder.FlowBuilder;
import org.ikasan.builder.ModuleBuilder;
import org.ikasan.spec.flow.Flow;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.stereotype.Component;

/**
 * The flow is the container for the components.
 * <p>
 * Some details of the components are defined here, but the majority of the configuration for components is delegated
 * to the ComponentFactory
 * <p>
 * This file is auto-generated by Ikasan Studio, do no edit.
 */
@Component("org.ikasan.studio.boot.flow.routerflow.RouterFlow")
public class RouterFlow {
    @Value("${module.name}")
    private String moduleName;

    @Resource
    BuilderFactory builderFactory;

    @Resource
    ComponentFactoryRouterFlow componentFactory;

    @Bean
    public Flow getRouterFlow() {
        ModuleBuilder moduleBuilder = builderFactory.getModuleBuilder(moduleName);
        FlowBuilder flowBuilder = moduleBuilder.getFlowBuilder("Router Flow");

        Flow routerFlow = flowBuilder
                .consumer("Connect to previous flow",
                        componentFactory.getConnectToPreviousFlow())
                .multiRecipientRouter("Both routes get it", componentFactory.getBothRoutesGetIt())
                .when("route1"
                        , builderFactory.getRouteBuilder().singleRecipientRouter("Either Or Router", componentFactory.getEitherOrRouter())
                                .when("odd"
                                        , builderFactory.getRouteBuilder().converter("String to email 1",
                                                        componentFactory.getStringToEmail1())
                                                .producer("output 1",
                                                        componentFactory.getOutput1())
                                )
                                .when("even"
                                        , builderFactory.getRouteBuilder().converter("String to email 2",
                                                        componentFactory.getStringToEmail2())
                                                .producer("output 2",
                                                        componentFactory.getOutput2())
                                )
                                .build()
                )
                .when("route2"
                        , builderFactory.getRouteBuilder().converter("String to email 3",
                                        componentFactory.getStringToEmail3())
                                .producer("output 3",
                                        componentFactory.getOutput3())
                )
                .build();
        return routerFlow;
    }
}