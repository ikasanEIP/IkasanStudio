package org.ikasan.studio.boot;

import jakarta.annotation.Resource;
import org.ikasan.builder.BuilderFactory;
import org.ikasan.builder.ModuleBuilder;
import org.ikasan.builder.component.ComponentBuilder;
import org.ikasan.spec.module.Module;
import org.ikasan.studio.boot.flow.filtersflow.FiltersFlow;
import org.ikasan.studio.boot.flow.routerflow.RouterFlow;
import org.ikasan.studio.boot.flow.splitterflow.SplitterFlow;
import org.ikasan.wiretap.listener.JobAwareFlowEventListener;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.ImportResource;
import org.springframework.context.annotation.Profile;

import java.util.ArrayList;

/**
 * The module config class defines details of the modules and identifies the flows but should not contain details
 * of the components in each flow.
 * <p>
 * This file is auto-generated by Ikasan Studio, do no edit.
 */
@Configuration("ModuleFactory")
@ImportResource({
        "classpath:h2-datasource-conf.xml",
        "classpath:ikasan-transaction-pointcut-ikasanMessageListener.xml"
})
public class ModuleConfig {
    @Value("${module.name}")
    private String moduleName;

    @Resource
    BuilderFactory builderFactory;
    @Resource
    SplitterFlow splitterFlow;
    @Resource
    FiltersFlow filtersFlow;
    @Resource
    RouterFlow routerFlow;

    @Bean
    public Module myModule() {
        ModuleBuilder moduleBuilder = builderFactory.getModuleBuilder(moduleName);

        ComponentBuilder componentBuilder = builderFactory.getComponentBuilder();

        Module module = moduleBuilder
                .addFlow(splitterFlow.getSplitterFlow())
                .addFlow(filtersFlow.getFiltersFlow())
                .addFlow(routerFlow.getRouterFlow())
                .build();
        return module;
    }

    @Bean
    @Profile("debug")
    public ApplicationRunner studioLoggingWiretapTriggers(
            JobAwareFlowEventListener listener) {
        return args -> {
            new ArrayList<>(listener.getTriggers()).stream()
                    .filter(trigger -> moduleName.equals(trigger.getModuleName()))
                    .filter(trigger -> "loggingJob".equals(trigger.getJobName()))
                    .filter(trigger -> trigger.getId() != null)
                    .forEach(trigger -> listener.deleteDynamicTrigger(trigger.getId()));
        };
    }

}
