package org.ikasan.studio.boot.flow.filtersflow;

import org.ikasan.builder.BuilderFactory;
import org.ikasan.builder.FlowBuilder;
import org.ikasan.builder.ModuleBuilder;
import org.ikasan.spec.flow.Flow;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.stereotype.Component;

import javax.annotation.Resource;

/**
 * The flow is the container for the components.
 * <p>
 * Some details of the components are defined here, but the majority of the configuration for components is delegated
 * to the ComponentFactory
 * <p>
 * This file is auto-generated by Ikasan Studio, do no edit.
 */
@Component("org.ikasan.studio.boot.flow.filtersflow.FiltersFlow")
public class FiltersFlow {
    @Value("${module.name}")
    private String moduleName;

    @Resource
    BuilderFactory builderFactory;

    @Resource
    ComponentFactoryFiltersFlow componentFactory;

    @Bean
    public Flow getFiltersFlow() {
        ModuleBuilder moduleBuilder = builderFactory.getModuleBuilder(moduleName);
        FlowBuilder flowBuilder = moduleBuilder.getFlowBuilder("Filters Flow");

        Flow filtersFlow = flowBuilder
                .consumer("connect to previous flow",
                        componentFactory.getConnectToPreviousFlow())
                .filter("Default filter every 5th",
                        componentFactory.getDefaultFilterEvery5th())
                .filter("filter every 4th",
                        componentFactory.getFilterEvery4th())
                .producer("connect to next flow",
                        componentFactory.getConnectToNextFlow())
                .build();
        return filtersFlow;
    }
}