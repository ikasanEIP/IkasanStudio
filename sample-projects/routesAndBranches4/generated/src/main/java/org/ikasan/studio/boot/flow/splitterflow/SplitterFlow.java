package org.ikasan.studio.boot.flow.splitterflow;

import org.ikasan.builder.BuilderFactory;
import org.ikasan.builder.FlowBuilder;
import org.ikasan.builder.ModuleBuilder;
import org.ikasan.spec.flow.Flow;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.stereotype.Component;

import javax.annotation.Resource;

/**
 * The flow is the container for the components.
 * <p>
 * Some details of the components are defined here, but the majority of the configuration for components is delegated
 * to the ComponentFactory
 * <p>
 * This file is auto-generated by Ikasan Studio, do no edit.
 */
@Component("org.ikasan.studio.boot.flow.splitterflow.SplitterFlow")
public class SplitterFlow {
    @Value("${module.name}")
    private String moduleName;

    @Resource
    BuilderFactory builderFactory;

    @Resource
    ComponentFactorySplitterFlow componentFactory;

    @Bean
    public Flow getSplitterFlow() {
        ModuleBuilder moduleBuilder = builderFactory.getModuleBuilder(moduleName);
        FlowBuilder flowBuilder = moduleBuilder.getFlowBuilder("Splitter Flow");

        Flow splitterFlow = flowBuilder
                .consumer("Message Trigger",
                        componentFactory.getMessageTrigger())
                .broker("Message for Batch Generator",
                        componentFactory.getMessageForBatchGenerator())
                .splitter("Default Split List to individuals",
                        componentFactory.getDefaultSplitListToIndividuals())
                .splitter("Standard split List to String",
                        componentFactory.getStandardSplitListToString())
                .producer("Connect to next flow",
                        componentFactory.getConnectToNextFlow())
                .build();
        return splitterFlow;
    }
}