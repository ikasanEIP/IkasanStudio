package org.ikasan.studio.core.generator;

import org.ikasan.studio.core.model.analysis.HarnessOverrides;
import org.ikasan.studio.core.model.analysis.TestJmsHarnessLinks;
import org.ikasan.studio.core.model.ikasan.instance.Module;

/** Harness-owned settings use a private namespace; loading the file alone enables nothing. */
public final class HarnessOverridesTemplate {
    public static final String JAVA_PATH = "generated/src/main/java/org/ikasan/studio/boot/StudioHarnessOverrides.java";
    public static final String PATH = "generated/src/main/resources/studio-harness.properties";
    private HarnessOverridesTemplate() { }
    public static String create(Module module) {
        StringBuilder text = new StringBuilder("""
                # Generated by Ikasan Studio. Configure harness use through Harness overrides in Studio.
                # This file does not replace component configuration or enable overrides on its own.
                studio.harness.ftp.host=127.0.0.1
                studio.harness.ftp.port=2121
                studio.harness.ftp.username=ikasan
                studio.harness.ftp.password=ikasan
                studio.harness.email.host=127.0.0.1
                studio.harness.email.port=1025
                """);
        for (var target : HarnessOverrides.targets(module)) {
            var flow = module.getFlows().stream().filter(f -> f.getFlowElementsNoExternalEndPoints().contains(target.element()))
                    .findFirst().orElseThrow();
            String prefix = "studio.harness.target." + target.id();
            text.append(prefix).append(".kind=").append(target.kind()).append("\n");
            text.append(prefix).append(".factory=org/ikasan/studio/boot/flow/").append(flow.getJavaPackageName())
                    .append("/ComponentFactory").append(flow.getJavaClassName()).append(".java\n");
            text.append(prefix).append(".label=").append(java.util.Base64.getEncoder().encodeToString(
                    target.label().getBytes(java.nio.charset.StandardCharsets.UTF_8))).append("\n");
            if ("JMS".equals(target.kind())) {
                String value = java.util.Objects.requireNonNull(
                        TestJmsHarnessLinks.destinationOverride(module, target.element()),
                        "JMS harness target has no destination: " + target.id());
                text.append("studio.harness.").append(target.id()).append(".destination=")
                        .append(value.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r")).append("\n");
            }
        }
        return text.toString();
    }

    public record LaunchTarget(String id, String kind, String factory, String label) { }

    /** Launch inventory avoids depending on an open Studio editor or a loaded live model. */
    public static java.util.List<LaunchTarget> launchTargets(String text) throws java.io.IOException {
        var properties = org.ikasan.studio.core.configuration.EnvironmentProperties.parse(text);
        var targets = new java.util.ArrayList<LaunchTarget>();
        String prefix = "studio.harness.target.";
        for (String key : new java.util.TreeSet<>(properties.stringPropertyNames())) {
            if (!key.startsWith(prefix) || !key.endsWith(".kind")) continue;
            String id = key.substring(prefix.length(), key.length() - ".kind".length());
            String factory = properties.getProperty(prefix + id + ".factory");
            String label = properties.getProperty(prefix + id + ".label");
            if (factory == null || label == null || !validFactoryPath(factory))
                throw new java.io.IOException("Invalid generated harness inventory; regenerate code.");
            try {
                targets.add(new LaunchTarget(id, properties.getProperty(key), factory,
                        new String(java.util.Base64.getDecoder().decode(label), java.nio.charset.StandardCharsets.UTF_8)));
            } catch (IllegalArgumentException failure) {
                throw new java.io.IOException("Invalid generated harness inventory; regenerate code.", failure);
            }
        }
        return java.util.List.copyOf(targets);
    }

    private static boolean validFactoryPath(String factory) {
        if (!factory.startsWith("org/ikasan/studio/boot/flow/") || !factory.endsWith(".java")) return false;
        for (String segment : factory.substring(0, factory.length() - 5).split("/", -1)) {
            if (segment.isEmpty() || !Character.isJavaIdentifierStart(segment.codePointAt(0))
                    || !segment.codePoints().allMatch(Character::isJavaIdentifierPart)) return false;
        }
        return true;
    }

    public static String javaSource() {
        return "package org.ikasan.studio.boot;\n"
                + "/** Generated harness adapter. Enable through Studio; never edit connection values here. */\n"
                + "public final class StudioHarnessOverrides {\n"
                + "private StudioHarnessOverrides() {}\n" + support() + "\n}\n";
    }

    /** Shared adapter for each pack's concrete endpoint implementation. */
    public static String support() {
        return """
                public static boolean isEnabled(String id) {
                    String selected = System.getProperty("studio.harness.components", "");
                    return java.util.Arrays.asList(selected.split(",")).contains(id);
                }
                public static <T> T apply(org.springframework.core.env.Environment studioHarnessEnvironment,
                        T endpoint, String id, String kind, boolean consumer) {
                    if (!isEnabled(id)) return endpoint;
                    try {
                        Object configuration = endpoint.getClass().getMethod("getConfiguration").invoke(endpoint);
                        String session = System.getProperty("studio.harness.session");
                        if (session == null) throw new IllegalStateException("Launch harness overrides through IntelliJ");
                        endpoint.getClass().getMethod("setConfiguredResourceId", String.class).invoke(endpoint,
                                "studio-harness-" + session + "-" + id + (consumer ? "-consumer" : "-producer"));
                        if (kind.equals("JMS")) {
                            studioHarnessSet(configuration, "DestinationJndiName", String.class,
                                    studioHarnessEnvironment.getRequiredProperty("studio.harness." + id + ".destination"));
                        } else if (kind.equals("Email")) {
                            String host = studioHarnessEnvironment.getRequiredProperty("studio.harness.email.host");
                            studioHarnessSet(configuration, "MailHost", String.class, host);
                            studioHarnessSet(configuration, "MailSmtpHost", String.class, host);
                            studioHarnessSet(configuration, "MailSmtpPort", int.class,
                                    studioHarnessEnvironment.getRequiredProperty("studio.harness.email.port", Integer.class));
                            studioHarnessSet(configuration, "MailTransportProtocol", String.class, "smtp");
                            studioHarnessSet(configuration, "User", String.class, null);
                            studioHarnessSet(configuration, "MailSmtpUser", String.class, null);
                            studioHarnessSet(configuration, "Password", String.class, null);
                            // A customer session map can otherwise retain SMTP authentication, TLS or a remote host.
                            studioHarnessSet(configuration, "ExtendedMailSessionProperties", java.util.Map.class,
                                    new java.util.HashMap<String, String>());
                        } else {
                            boolean sftp = kind.equals("SFTP");
                            String prefix = sftp ? "studio.test.sftp." : "studio.harness.ftp.";
                            studioHarnessSet(configuration, "RemoteHost", String.class, sftp ? "127.0.0.1" :
                                    studioHarnessEnvironment.getRequiredProperty(prefix + "host"));
                            studioHarnessSet(configuration, "RemotePort", Integer.class, sftp ?
                                    Integer.valueOf(System.getProperty(prefix + "port")) :
                                    studioHarnessEnvironment.getRequiredProperty(prefix + "port", Integer.class));
                            studioHarnessSet(configuration, "Username", String.class, sftp ? "ikasan" :
                                    studioHarnessEnvironment.getRequiredProperty(prefix + "username"));
                            studioHarnessSet(configuration, "Password", String.class, sftp ?
                                    System.getProperty(prefix + "password") : studioHarnessEnvironment.getRequiredProperty(prefix + "password"));
                            if (sftp) {
                                studioHarnessSet(configuration, "PrivateKeyFilename", String.class, "");
                                studioHarnessSet(configuration, "PrivateKeyPassphrase", String.class, "");
                                studioHarnessSet(configuration, "KnownHostsFilename", String.class, System.getProperty(prefix + "knownHosts"));
                                studioHarnessSet(configuration, "PreferredKeyExchangeAlgorithm", String.class, null);
                            } else {
                                studioHarnessSet(configuration, "PasswordFilePath", String.class, null);
                            }
                            // Alternate failover must stay on the local harness too.
                            for (var method : configuration.getClass().getMethods()) {
                                if (method.getParameterCount() == 1 && method.getName().startsWith("setAlternate")) {
                                    String primary = "get" + method.getName().substring("setAlternate".length());
                                    try {
                                        Object value = configuration.getClass().getMethod(primary).invoke(configuration);
                                        method.invoke(configuration, value);
                                    } catch (NoSuchMethodException unused) {
                                        // There is no equivalent primary setting to mirror.
                                    }
                                }
                            }
                            String directory = "component-" + id;
                            String home = System.getProperty(sftp ? "studio.test.sftp.home" : "studio.harness.ftp.home");
                            if (home == null) throw new IllegalStateException("Start the local file harness before launching");
                            java.nio.file.Files.createDirectories(java.nio.file.Path.of(home).resolve(directory));
                            studioHarnessSet(configuration, consumer ? "SourceDirectory" : "OutputDirectory", String.class, "/" + directory);
                            if (consumer) {
                                for (var method : configuration.getClass().getMethods()) {
                                    if (method.getName().equals("setSourceDirectoryURLFactory") && method.getParameterCount() == 1)
                                        method.invoke(configuration, new Object[]{null});
                                }
                                studioHarnessSet(configuration, "MinAge", Long.class, 0L);
                            }
                        }
                        return endpoint;
                    } catch (Exception failure) {
                        throw new IllegalStateException("Cannot apply " + kind + " harness override for " + id, failure);
                    }
                }
                private static void studioHarnessSet(Object configuration, String name, Class<?> type, Object value) throws Exception {
                    configuration.getClass().getMethod("set" + name, type).invoke(configuration, value);
                }
                """;
    }
}
